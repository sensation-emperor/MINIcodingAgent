TEST(TestGeneratorTest, WriteTestFileCreatesFile) {
    TestGenerator gen;
    ParsedSymbol sym;
    sym.qualified_name = "aios::TestFunc";
    sym.return_type    = "bool";
    sym.param_types    = {"int"};
    sym.is_method      = false;

    std::string output_dir = std::filesystem::temp_directory_path().string();
    auto result = gen.generateTests({sym}, output_dir, "WriteTest");

    EXPECT_TRUE(result.success);
    EXPECT_TRUE(std::filesystem::exists(result.output_file_path));
    // Cleanup
    std::filesystem::remove(result.output_file_path);
}

TEST(TestGeneratorTest, ParseGccDiagnosticErrors) {
    TestGenerator gen;
    std::string output =
        "/home/user/project/src/foo.cpp:42:10: error: 'bar' was not declared in this scope\n"
        "/home/user/project/src/foo.cpp:55:5: warning: unused variable 'x' [-Wunused-variable]\n";

    auto report = gen.parseDiagnostics(output, "gcc");

    EXPECT_TRUE(report.has_errors);
    EXPECT_EQ(report.error_count, 1);
    EXPECT_EQ(report.warning_count, 1);
    ASSERT_FALSE(report.diagnostics.empty());

    const auto& d = report.diagnostics[0];
    EXPECT_EQ(d.line, 42);
    EXPECT_EQ(d.column, 10);
    EXPECT_EQ(d.severity, DiagnosticSeverity::Error);
    EXPECT_NE(d.message.find("bar"), std::string::npos);
    EXPECT_FALSE(d.suggested_fix.empty());
}

TEST(TestGeneratorTest, ParseMsvcDiagnosticErrors) {
    TestGenerator gen;
    std::string output =
        "C:\\project\\src\\bar.cpp(17): error C2065: 'foo': undeclared identifier\n"
        "C:\\project\\src\\bar.cpp(30): warning C4101: 'x': unreferenced local variable\n";

    auto report = gen.parseDiagnostics(output, "msvc");

    EXPECT_TRUE(report.has_errors);
    EXPECT_EQ(report.error_count, 1);
    EXPECT_EQ(report.warning_count, 1);
    EXPECT_EQ(report.diagnostics[0].error_code, "C2065");
    EXPECT_EQ(report.diagnostics[0].line, 17);
}

TEST(TestGeneratorTest, RemediationActionsIsValidJson) {
    TestGenerator gen;
    DiagnosticsReport report;
    CompilerDiagnostic d;
    d.severity = DiagnosticSeverity::Error;
    d.file_path = "src/foo.cpp";
    d.line = 10;
    d.message = "undefined reference to 'bar'";
    d.suggested_fix = "Add missing implementation or link library.";
    report.diagnostics.push_back(d);
    report.has_errors = true;
    report.error_count = 1;

    std::string json_out = gen.toRemediationActions(report);
    EXPECT_FALSE(json_out.empty());
    EXPECT_NE(json_out.find("fix_compiler_error"), std::string::npos);
    EXPECT_NE(json_out.find("undefined reference"), std::string::npos);
}

TEST(TestGeneratorTest, EmptyDiagnosticsNoErrors) {
    TestGenerator gen;
    auto report = gen.parseDiagnostics("Build succeeded.\n[ 100%] Linking\n", "gcc");
    EXPECT_FALSE(report.has_errors);
    EXPECT_EQ(report.error_count, 0);
}
