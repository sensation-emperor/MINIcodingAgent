TEST(TestGeneratorTest, GenerateTestCaseForMethod) {
    TestGenerator gen;
    ParsedSymbol sym;
    sym.qualified_name = "aios::VectorStore::search";
    sym.return_type    = "std::vector<VectorSearchResult>";
    sym.param_types    = {"std::string_view", "size_t"};
    sym.is_method      = true;
    sym.class_name     = "VectorStore";
    sym.file_path      = "vector/VectorStore.h";

    auto tc = gen.generateTestCase(sym, "AutoGenerated");

    EXPECT_EQ(tc.test_suite_name, "AutoGenerated");
    EXPECT_FALSE(tc.test_name.empty());
    EXPECT_NE(tc.test_body.find("VectorStore"), std::string::npos);
    EXPECT_FALSE(tc.include_headers.empty());
}

